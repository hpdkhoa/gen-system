package mobile

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/hpdkhoa/gen-system/generator/internal/schema"
)

// BackendPort is the port the generated Go backend listens on when PORT is not
// set (schema.DefaultBackendPort, the default in backend/main.go written by
// internal/engine). port_v2658_test.go compares the two, so they cannot drift.
const BackendPort = schema.DefaultBackendPort

// configJS is mobile/config.js, the one place the mobile app reads the
// backend address from. 10.0.2.2 reaches the host machine from the Android
// emulator; a real device needs the host's LAN address here.
const configJS = `// Generated by gen-system. The backend address every screen calls.
// 10.0.2.2 reaches the host machine from the Android emulator. On a real
// device, put the LAN address of the machine that runs backend/main.go here.
// gen-system writes this file only when it is missing, so a change here stays.
export const API_BASE_URL = "http://10.0.2.2:` + BackendPort + `";
`

// GenerateScreen writes mobile/<entity>_screen.js, a React Native form and
// list for one entity, and mobile/config.js when it is missing. It returns an
// error when a file cannot be written.
func GenerateScreen(e schema.Entity, path string) error {

	name := e.Name
	lower := strings.ToLower(name)
	// v26.58 (D035): the request path comes from schema.CollectionPath, the
	// rule the generated backend registers its routes with. The old
	// strings.ToLower(name) + "s" gave /addresss for Address and /order_items
	// for Order_Item, while the backend served /address and /orderitems, so
	// every request got 404.
	coll := schema.CollectionPath(name)

	content := fmt.Sprintf(`


import { View, Text, TextInput, Button } from "react-native";
import { useState, useEffect } from "react";
import { API_BASE_URL } from "./config";

export default function %sScreen() {

const [form, setForm] = useState({});
const [list, setList] = useState([]);

useEffect(() => {
fetch(API_BASE_URL + "%s")
.then(r => r.json())
.then(setList);
}, []);

return ( <View>


  <Text>%s Form</Text>


`, name, coll, name)

	for _, f := range e.Fields {
		content += fmt.Sprintf(`
  <TextInput
    placeholder="%s"
    onChangeText={v => setForm({...form, %s: v})}
  />


`, f.Name, jsKey(schema.JSONKey(f.Name))) // v26.58 (D035): send the model's JSON key, not the raw field name
	}

	content += fmt.Sprintf(`
  <Button title="Create" onPress={() => {
    fetch(API_BASE_URL + "%s", {
      method: "POST",
      body: JSON.stringify(form)
    });
  }} />

  <Text>List</Text>

  {list.map(i => (
    <Text key={i.id}>{JSON.stringify(i)}</Text>
  ))}

</View>


);
}
`, coll)

	// v26.57 (D003): create mobile/ first and report a failed write. In an agent
	// build into a fresh folder nothing created mobile/ before the first
	// generate_mobile task, so the old bare os.WriteFile failed without a
	// message and App.js imported a screen that did not exist.
	dir := filepath.Join(path, "mobile")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("mobile screen for %s: %w", name, err)
	}
	file := filepath.Join(dir, lower+"_screen.js")
	if err := os.WriteFile(file, []byte(content), 0o644); err != nil {
		return fmt.Errorf("mobile screen for %s: %w", name, err)
	}
	// v26.58 (D036): the screens called the fixed address 10.0.2.2:28080, but
	// the generated backend/main.go listens on :8080, so every request failed.
	// They now read API_BASE_URL from mobile/config.js, which names
	// BackendPort. The file is written only when missing, so an address the
	// user set for a real device survives a regeneration.
	cfg := filepath.Join(dir, "config.js")
	if _, err := os.Stat(cfg); os.IsNotExist(err) {
		if err := os.WriteFile(cfg, []byte(configJS), 0o644); err != nil {
			return fmt.Errorf("mobile config: %w", err)
		}
	}
	return nil
}

// jsKey writes a JSON key as a JavaScript object literal key, quoted when the
// key is not a valid identifier (a JSON key can start with a digit).
func jsKey(key string) string {
	if key != "" && (key[0] < '0' || key[0] > '9') {
		return key
	}
	return `"` + key + `"`
}
