// generator/internal/planner_v2/summarize_v2324_test.go — v23.24 (task 4A):
// tests for recovering the entity set directly from generated model structs,
// the fallback used when no IR snapshot is present in the working dir.
package planner_v2

import "testing"

const sampleModelOrder = `// Code generated by gen-system. DO NOT EDIT.
package model

type Order struct {
	ID int ` + "`json:\"id\"`" + `
	Total float64 ` + "`json:\"total\"`" + `
	Status string ` + "`json:\"status\"`" + `
	DueDate time.Time ` + "`json:\"due_date\"`" + `
	Active bool ` + "`json:\"active\"`" + `
}
`

func TestParseModelStructs_TypesAndTags_v2324(t *testing.T) {
	ents := parseModelStructs(sampleModelOrder)
	if len(ents) != 1 {
		t.Fatalf("expected 1 entity, got %d", len(ents))
	}
	o := ents[0]
	if o.Name != "Order" {
		t.Fatalf("expected Order, got %s", o.Name)
	}
	want := map[string]string{
		"id":       "int",
		"total":    "float",
		"status":   "string",
		"due_date": "time",
		"active":   "bool",
	}
	if len(o.Fields) != len(want) {
		t.Fatalf("expected %d fields, got %d (%+v)", len(want), len(o.Fields), o.Fields)
	}
	for _, f := range o.Fields {
		if want[f.Name] != f.Type {
			t.Errorf("field %s: want type %s, got %s", f.Name, want[f.Name], f.Type)
		}
	}
}

func TestGoTypeToSchemaType_v2324(t *testing.T) {
	cases := map[string]string{
		"int": "int", "int64": "int", "float64": "float", "float32": "float",
		"bool": "bool", "time.Time": "time", "string": "string",
		"*string": "string", "SomethingWeird": "string",
	}
	for in, want := range cases {
		if got := goTypeToSchemaType(in); got != want {
			t.Errorf("goTypeToSchemaType(%q) = %q, want %q", in, got, want)
		}
	}
}

// Multiple structs in one file are all recovered.
func TestParseModelStructs_Multiple_v2324(t *testing.T) {
	src := `package model
type A struct {
	ID int ` + "`json:\"id\"`" + `
}
type B struct {
	ID int ` + "`json:\"id\"`" + `
	Name string ` + "`json:\"name\"`" + `
}
`
	ents := parseModelStructs(src)
	if len(ents) != 2 {
		t.Fatalf("expected 2 entities, got %d", len(ents))
	}
	if ents[0].Name != "A" || ents[1].Name != "B" {
		t.Fatalf("unexpected names: %s, %s", ents[0].Name, ents[1].Name)
	}
}
