// generator/internal/engine/mobile_project.go, v23.13 (Phase 5): wraps the
// loose generated mobile/ screens in a minimal React Native project so a JS
// bundle can be produced. Boundary: this gates a JS bundle only, not a
// signed .apk/.ipa. Producing an installable app needs the Android/iOS SDKs and
// signing keys, which are out of scope (and absent in any offline build box).
// The scaffold is what makes `npx react-native bundle` possible; running it is a
// verify-on-box step.
package engine

import (
	"errors"
	"os"
	"path/filepath"
	"strings"

	"github.com/hpdkhoa/gen-system/generator/internal/schema"
)

// GenerateMobileProject writes package.json, an entry point, and an App that
// renders the generated screens, so the mobile/ tree can be bundled.
//
// v26.59 (N07): the MkdirAll error returned without a message and every
// writeFileMk error was dropped, so the task counted as a success with the
// mobile project missing. The function now returns the MkdirAll error, or the
// joined write errors, as GenerateWebProject does since D030.
func GenerateMobileProject(entities []schema.Entity, rootPath string) error {
	mDir := filepath.Join(rootPath, "mobile")
	if err := os.MkdirAll(mDir, 0755); err != nil {
		return err
	}
	return errors.Join(
		writeFileMk(filepath.Join(mDir, "package.json"), mobilePackageJSON),
		writeFileMk(filepath.Join(mDir, "index.js"), mobileIndexJS),
		writeFileMk(filepath.Join(mDir, "app.json"), mobileAppJSON),
		writeFileMk(filepath.Join(mDir, "App.js"), mobileAppJS(entities)),
		writeFileMk(filepath.Join(mDir, "metro.config.js"), mobileMetroConfig),
		writeFileMk(filepath.Join(mDir, "babel.config.js"), mobileBabelConfig),
		writeFileMk(filepath.Join(mDir, "BUNDLE_ONLY.md"), mobileBoundaryNote),
	)
}

const mobilePackageJSON = `{
  "name": "generated-mobile",
  "private": true,
  "version": "0.1.0",
  "scripts": {
    "bundle:android": "react-native bundle --platform android --dev false --entry-file index.js --bundle-output ./dist/mobile.android.bundle --assets-dest ./dist",
    "bundle:ios": "react-native bundle --platform ios --dev false --entry-file index.js --bundle-output ./dist/mobile.ios.jsbundle --assets-dest ./dist"
  },
  "dependencies": {
    "react": "18.3.1",
    "react-native": "0.74.5"
  },
  "devDependencies": {
    "@babel/core": "7.25.2",
    "@babel/preset-env": "7.25.4",
    "@babel/runtime": "7.25.6",
    "@react-native/babel-preset": "0.74.87",
    "@react-native/metro-config": "0.74.87",
    "metro-react-native-babel-preset": "0.77.0"
  }
}
`

const mobileIndexJS = `// Generated entry point. Registers the root component with React Native's
// AppRegistry so the JS bundle has a defined entry.
import { AppRegistry } from "react-native";
import App from "./App";
import { name as appName } from "./app.json";

AppRegistry.registerComponent(appName, () => App);
`

const mobileAppJSON = `{
  "name": "generatedmobile",
  "displayName": "Generated Mobile"
}
`

const mobileMetroConfig = `const { getDefaultConfig } = require("@react-native/metro-config");
module.exports = getDefaultConfig(__dirname);
`

const mobileBabelConfig = `module.exports = {
  presets: ["@react-native/babel-preset"],
};
`

// mobileAppJS renders one screen per entity. The per-entity screen files
// (<lower>_screen.js) are written by mobile.GenerateScreen; this App imports and
// stacks them in a ScrollView.
func mobileAppJS(entities []schema.Entity) string {
	var sb strings.Builder
	sb.WriteString("// Generated by gen-system. Root component stacking the entity screens.\n")
	sb.WriteString(`import React from "react";` + "\n")
	sb.WriteString(`import { ScrollView } from "react-native";` + "\n")
	for _, e := range entities {
		lower := strings.ToLower(e.Name)
		sb.WriteString(`import ` + e.Name + `Screen from "./` + lower + `_screen";` + "\n")
	}
	sb.WriteString("\nexport default function App() {\n")
	sb.WriteString("  return (\n    <ScrollView>\n")
	for _, e := range entities {
		sb.WriteString("      <" + e.Name + "Screen />\n")
	}
	sb.WriteString("    </ScrollView>\n  );\n}\n")
	return sb.String()
}

const mobileBoundaryNote = `# Mobile layer — JS bundle only

This React Native project is generated as scaffolding so you can produce a
JavaScript **bundle**:

    npm ci
    npm run bundle:android   # -> dist/mobile.android.bundle

That bundle is what gen-system's build-all.sh / bundle.sh package.

**It is NOT a signed, installable app.** Producing an .apk or .ipa requires the
Android SDK / Xcode toolchains and signing keys on your machine — those are out
of scope for gen-system's offline artifact build. Open the project in the native
toolchain when you want an installable binary.
`
