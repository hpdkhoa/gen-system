// postgresEnabled reports whether to also generate the Postgres backend.
func postgresEnabled() bool {
	return strings.EqualFold(os.Getenv("GEN_BACKEND"), "postgres")
}

// sqlType maps a schema field type to a Postgres column type.
func sqlType(t string) string {
	switch strings.ToLower(t) {
	case "int", "integer":
		return "INTEGER"
	case "bool", "boolean":
		return "BOOLEAN"
	case "float", "float64", "double", "decimal":
		return "DOUBLE PRECISION"
	case "time", "datetime", "date", "timestamp":
		return "TIMESTAMPTZ"
	default:
		return "TEXT"
	}
}

// emitDBConnector writes backend/internal/db/db.go: it loads the project .env
// (no external dependency, a small built-in parser) and opens a *sql.DB from
// the connection string, looking at DATABASE_URL first, then DB_URL (the name
// the generated .env writes), then a local default.
//
// v23.15: always (re)write the connector. The old early-return left a stale,
// possibly older-format db.go (e.g. one reading DB_URL + db.Init()) in a reused
// dir. v23.15 also adds the .env loader + DB_URL fallback so the value the
// generated .env actually contains reaches the app (previously .env wrote
// DB_URL but the connector only read DATABASE_URL, so .env was silently
// ignored).
//
// v26.58 (D028): the ping error held the full DSN, so log.Fatal in the generated
// main printed the user name and password. The generated dsnTarget names only
// host and database, and says "the configured database" for a DSN it cannot
// parse as a URL (the key=value form may hold a password too).
func emitDBConnector(path string) error {
	p := filepath.Join(path, "backend/internal/db/db.go")
	src := `// Code generated by gen-system. DO NOT EDIT.
package db

import (
	"bufio"
	"database/sql"
	"fmt"
	"net/url"
	"os"
	"strings"

	_ "github.com/lib/pq"
)

// loadDotEnv reads KEY=VALUE lines from the given file and sets any that are not
// already present in the environment (real env vars always win). It is a tiny,
// dependency-free .env loader: blank lines and lines starting with '#' are
// skipped, surrounding quotes on the value are stripped, and a leading
// "export " is tolerated. Missing file is not an error.
func loadDotEnv(file string) {
	f, err := os.Open(file)
	if err != nil {
		return
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		line = strings.TrimPrefix(line, "export ")
		eq := strings.IndexByte(line, '=')
		if eq <= 0 {
			continue
		}
		key := strings.TrimSpace(line[:eq])
		val := strings.TrimSpace(line[eq+1:])
		val = strings.Trim(val, "\"'")
		if key == "" {
			continue
		}
		if _, ok := os.LookupEnv(key); !ok {
			os.Setenv(key, val)
		}
	}
}

// dsn resolves the Postgres connection string. Precedence: DATABASE_URL, then
// DB_URL (the key the generated .env uses), then a local-dev default.
func dsn() string {
	if v := os.Getenv("DATABASE_URL"); v != "" {
		return v
	}
	if v := os.Getenv("DB_URL"); v != "" {
		return v
	}
	return "postgres://postgres:postgres@localhost:5432/app?sslmode=disable"
}

// Open loads .env (searching the working dir and the parent, so it works whether
// you run from the project root or from backend/) and connects to Postgres.
func Open() (*sql.DB, error) {
	loadDotEnv(".env")
	loadDotEnv("../.env")
	conn := dsn()
	d, err := sql.Open("postgres", conn)
	if err != nil {
		return nil, fmt.Errorf("open db: %w", err)
	}
	if err := d.Ping(); err != nil {
		return nil, fmt.Errorf("ping db (%s): %w", dsnTarget(conn), err)
	}
	return d, nil
}

// dsnTarget names the host and database of a connection string for an error
// message. It never returns the user name or the password.
func dsnTarget(conn string) string {
	u, err := url.Parse(conn)
	if err != nil || u.Host == "" {
		return "the configured database"
	}
	return "host " + u.Host + ", database " + strings.TrimPrefix(u.Path, "/")
}
`
	return writeFileMk(p, src)
}

// genMigration writes backend/migrations/<NNN>_<entity>.sql with a CREATE TABLE
// matching the entity. Auto-applied on boot by the generated main (postgres).
//
// v23.8: belongsTo relations contribute an FK column (via fieldsForEntity).
// The REFERENCES constraint itself is emitted separately by
// genForeignKeyMigration (a trailing migration) so it runs after every table
// exists, regardless of entity declaration order.
func genPGMigration(e schema.Entity, idx int, path string) error {
	table := tableName(e)
	var cols []string
	cols = append(cols, "id SERIAL PRIMARY KEY")
	for _, f := range fieldsForEntity(e) {
		cols = append(cols, fmt.Sprintf("%s %s", jsonTag(f.Name), sqlType(f.Type)))
	}
	sql := fmt.Sprintf("CREATE TABLE IF NOT EXISTS %s (\n  %s\n);\n", table, strings.Join(cols, ",\n  "))
	return writeFileMk(filepath.Join(path, fmt.Sprintf("backend/internal/db/migrations/%03d_%s.sql", idx, table)), sql)
}

// genForeignKeyMigration writes a single trailing migration adding a FK
// constraint for every belongsTo relation across all entities. It runs after
// all CREATE TABLEs (high index 900) so referenced tables always exist, and
// each ALTER is wrapped in a DO block that checks pg_constraint first, making
// it idempotent (Postgres has no ADD CONSTRAINT IF NOT EXISTS). Emits nothing
// when there are no belongsTo relations.
func genForeignKeyMigration(entities []schema.Entity, path string) error {
	var stmts []string
	for _, e := range entities {
		table := tableName(e)
		for _, rel := range e.Relations {
			if !strings.EqualFold(rel.Type, "belongsTo") || strings.TrimSpace(rel.Target) == "" {
				continue
			}
			name := rel.ForeignKey
			if strings.TrimSpace(name) == "" {
				name = rel.Target + "ID"
			}
			// v23.26 (task E fix, corrected): the FK column must equal the column
			// genTable actually emitted. genTable names columns jsonTag(f.Name)
			// over fieldsForEntity(e), which dedupes. So if the schema declares
			// an explicit FK field (e.g. "userID") that field wins over the
			// synthesized relation field and the column follows the explicit
			// spelling. Re-deriving the column from rel.ForeignKey alone (via
			// splitCamel) disagreed with the table whenever an explicit field was
			// present. We instead resolve against the real emitted fields so the
			// ALTER TABLE always references the column that exists.
			col := resolveFKColumn(e, name)
			targetTable := plural(routeName(rel.Target))
			constraint := fmt.Sprintf("fk_%s_%s", table, col)
			// v23.27 (task E fix): emit a plain, idempotent two-statement form
			// instead of an anonymous `DO $$ … $$` block. lib/pq executes an
			// anonymous dollar-quoted DO block over the extended protocol in a way
			// that silently does nothing (Exec returns no error but the constraint is
			// never added). That is why a live orphan insert was accepted even
			// though Migrate() returned nil. DROP CONSTRAINT IF EXISTS is itself
			// idempotent and needs no procedural block, and ADD CONSTRAINT then
			// reliably creates the FK. Each statement is run separately by the
			// migration runner (it splits on ';').
			stmts = append(stmts, fmt.Sprintf(
				"ALTER TABLE %s DROP CONSTRAINT IF EXISTS %s;\n"+
					"ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s(id);",
				table, constraint, table, constraint, col, targetTable))
		}
	}
	if len(stmts) == 0 {
		return nil
	}
	body := strings.Join(stmts, "\n\n") + "\n"
	return writeFileMk(filepath.Join(path, "backend/internal/db/migrations/900_foreign_keys.sql"), body)
}

// genStorePostgres writes backend/internal/store/<slug>_pg.go: a database/sql
// implementation of the same CRUD surface as the in-memory store, satisfying
// the per-entity store interface used by the handler.
func genStorePostgres(e schema.Entity, path string) error {
	n := typeName(e.Name)
	table := tableName(e)

	// column list (excluding id) and scan/placeholder helpers
	var cols []string
	for _, f := range fieldsForEntity(e) {
		cols = append(cols, jsonTag(f.Name))
	}
	colList := strings.Join(cols, ", ")
	// placeholders $1.. for insert/update
	ph := make([]string, len(cols))
	for i := range cols {
		ph[i] = fmt.Sprintf("$%d", i+1)
	}
	phList := strings.Join(ph, ", ")
	// "col = $n" set list for update (id is last param)
	set := make([]string, len(cols))
	for i, c := range cols {
		set[i] = fmt.Sprintf("%s = $%d", c, i+1)
	}
	setList := strings.Join(set, ", ")

	// field accessors for scan/args (ID + fields)
	scanTargets := []string{"&m.ID"}
	argList := []string{}
	for _, f := range fieldsForEntity(e) {
		scanTargets = append(scanTargets, "&m."+exportName(f.Name))
		argList = append(argList, "m."+exportName(f.Name))
	}
	scan := strings.Join(scanTargets, ", ")
	args := strings.Join(argList, ", ")
	allCols := "id" + func() string {
		if colList == "" {
			return ""
		}
		return ", " + colList
	}()

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen-system. DO NOT EDIT.\npackage store\n\n")
	fmt.Fprintf(&b, "import (\n\t\"database/sql\"\n\n\t\"app/backend/internal/model\"\n)\n\n")
	fmt.Fprintf(&b, "type %sPGStore struct{ db *sql.DB }\n\n", n)
	fmt.Fprintf(&b, "func New%sPGStore(db *sql.DB) *%sPGStore { return &%sPGStore{db: db} }\n\n", n, n, n)
	// v26.58 (D026): an entity whose only field is id (or with no field) has no
	// column besides id. The old templates then wrote `INSERT INTO t () VALUES ()`,
	// a trailing ", )" argument list and `UPDATE t SET  WHERE`, so the store did
	// not parse. DEFAULT VALUES is the valid SQL for a row with no given column,
	// and Update has nothing to set, so it only checks that the row exists.
	insertSQL := fmt.Sprintf("INSERT INTO %s (%s) VALUES (%s) RETURNING id", table, colList, phList)
	insertArgs := ", " + args
	if len(cols) == 0 {
		insertSQL = fmt.Sprintf("INSERT INTO %s DEFAULT VALUES RETURNING id", table)
		insertArgs = ""
	}
	// Create
	fmt.Fprintf(&b, "func (s *%sPGStore) Create(m model.%s) (model.%s, error) {\n\tif err := s.db.QueryRow(`%s`%s).Scan(&m.ID); err != nil {\n\t\treturn model.%s{}, err\n\t}\n\treturn m, nil\n}\n\n",
		n, n, n, insertSQL, insertArgs, n)
	// List
	// v26.58 (D027): List returned the rows it had when Query failed and skipped
	// rows that failed to scan, so a database outage looked like an empty table
	// (200 with []). It now returns the query, scan and rows.Err errors, and the
	// handler answers 500.
	fmt.Fprintf(&b, "func (s *%sPGStore) List() ([]model.%s, error) {\n\tout := []model.%s{}\n\trows, err := s.db.Query(`SELECT %s FROM %s ORDER BY id`)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\tdefer rows.Close()\n\tfor rows.Next() {\n\t\tvar m model.%s\n\t\tif err := rows.Scan(%s); err != nil {\n\t\t\treturn nil, err\n\t\t}\n\t\tout = append(out, m)\n\t}\n\tif err := rows.Err(); err != nil {\n\t\treturn nil, err\n\t}\n\treturn out, nil\n}\n\n",
		n, n, n, allCols, table, n, scan)
	// Get
	fmt.Fprintf(&b, "func (s *%sPGStore) Get(id int) (model.%s, bool) {\n\tvar m model.%s\n\terr := s.db.QueryRow(`SELECT %s FROM %s WHERE id=$1`, id).Scan(%s)\n\tif err != nil {\n\t\treturn model.%s{}, false\n\t}\n\treturn m, true\n}\n\n",
		n, n, n, allCols, table, scan, n)
	// Update
	if len(cols) == 0 {
		// v26.58 (D026): nothing to set; answer like the in-memory store, true
		// when the row exists.
		fmt.Fprintf(&b, "func (s *%sPGStore) Update(id int, m model.%s) (model.%s, bool) {\n\tif err := s.db.QueryRow(`SELECT id FROM %s WHERE id=$1`, id).Scan(&m.ID); err != nil {\n\t\treturn model.%s{}, false\n\t}\n\treturn m, true\n}\n\n",
			n, n, n, table, n)
	} else {
		fmt.Fprintf(&b, "func (s *%sPGStore) Update(id int, m model.%s) (model.%s, bool) {\n\tres, err := s.db.Exec(`UPDATE %s SET %s WHERE id=$%d`, %s, id)\n\tif err != nil {\n\t\treturn model.%s{}, false\n\t}\n\tif rows, _ := res.RowsAffected(); rows == 0 {\n\t\treturn model.%s{}, false\n\t}\n\tm.ID = id\n\treturn m, true\n}\n\n",
			n, n, n, table, setList, len(cols)+1, args, n, n)
	}
	// Delete
	fmt.Fprintf(&b, "func (s *%sPGStore) Delete(id int) bool {\n\tres, err := s.db.Exec(`DELETE FROM %s WHERE id=$1`, id)\n\tif err != nil {\n\t\treturn false\n\t}\n\trows, _ := res.RowsAffected()\n\treturn rows > 0\n}\n",
		n, table)

	return writeFileMk(filepath.Join(path, "backend/internal/store/"+routeName(e.Name)+"_pg.go"), b.String())
}

// emitStoreInterface writes a per-entity store interface so the handler can
// hold either the in-memory or the Postgres implementation. Only emitted in
// postgres mode (in memory-only mode the handler uses the concrete store).
func emitStoreInterfaces(entities []schema.Entity, path string) error {
	var b strings.Builder
	b.WriteString("// Code generated by gen-system. DO NOT EDIT.\npackage store\n\n")
	b.WriteString("import \"app/backend/internal/model\"\n\n")
	for _, e := range entities {
		n := typeName(e.Name)
		// v26.58 (D027): List has an error result so a failed query reaches the handler.
		fmt.Fprintf(&b, "type %sCRUD interface {\n\tCreate(m model.%s) (model.%s, error)\n\tList() ([]model.%s, error)\n\tGet(id int) (model.%s, bool)\n\tUpdate(id int, m model.%s) (model.%s, bool)\n\tDelete(id int) bool\n}\n\n", n, n, n, n, n, n, n)
	}
	return writeFileMk(filepath.Join(path, "backend/internal/store/interfaces.go"), b.String())
}

// emitMigrationRunner writes backend/internal/db/migrate.go that applies every
// backend/migrations/*.sql in order (embedded at build time).
func emitMigrationRunner(path string) error {
	p := filepath.Join(path, "backend/internal/db/migrate.go")
	src := `// Code generated by gen-system. DO NOT EDIT.
package db

import (
	"database/sql"
	"embed"
	"sort"
	"strings"
)

//go:embed migrations/*.sql
var migrationsFS embed.FS

// Migrate applies all embedded migrations in filename order. Idempotent because
// table migrations use CREATE TABLE IF NOT EXISTS and the FK migration uses
// DROP CONSTRAINT IF EXISTS + ADD CONSTRAINT. Each migration file is split into
// individual statements on ';' and executed one at a time — lib/pq's Exec does
// NOT reliably apply multiple statements (or an anonymous DO block) in a single
// call, which previously left FK constraints silently uncreated.
func Migrate(d *sql.DB) error {
	entries, err := migrationsFS.ReadDir("migrations")
	if err != nil {
		return nil // no migrations embedded
	}
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		names = append(names, e.Name())
	}
	sort.Strings(names)
	for _, name := range names {
		b, err := migrationsFS.ReadFile("migrations/" + name)
		if err != nil {
			return err
		}
		for _, stmt := range strings.Split(string(b), ";") {
			s := strings.TrimSpace(stmt)
			if s == "" {
				continue
			}
			if _, err := d.Exec(s); err != nil {
				return err
			}
		}
	}
	return nil
}
`
	return writeFileMk(p, src)
}
