// webAppTSX builds a typed App that imports the generated entity types and the
// typed API client, listing each entity. It matches the exact Phase 2 client
// contract: the client exports a per-entity object `<lcFirst>Api` with a
// `.list()` method, and the types barrel exports `<Entity>` (original-case
// name). Verified against frontend/typescript.go GenerateAPIClient.
func webAppTSX(entities []schema.Entity) string {
	var sb strings.Builder
	sb.WriteString(`import React, { useEffect, useState } from "react";` + "\n")
	if len(entities) > 0 {
		// import the per-entity client objects: { orderApi, productApi }
		clientNames := make([]string, 0, len(entities))
		typeNames := make([]string, 0, len(entities))
		for _, e := range entities {
			clientNames = append(clientNames, " "+lcFirstWeb(e.Name)+"Api")
			typeNames = append(typeNames, " "+e.Name)
		}
		sb.WriteString(`import {` + strings.Join(clientNames, ",") + ` } from "./api/client";` + "\n")
		sb.WriteString(`import type {` + strings.Join(typeNames, ",") + ` } from "./types";` + "\n")
	}
	sb.WriteString("\nexport function App() {\n")
	sb.WriteString("  return (\n    <main>\n      <h1>Generated App</h1>\n")
	for _, e := range entities {
		sb.WriteString("      <" + e.Name + "List />\n")
	}
	sb.WriteString("    </main>\n  );\n}\n\n")

	// One typed list component per entity, using <entity>Api.list().
	for _, e := range entities {
		name := e.Name
		apiObj := lcFirstWeb(e.Name) + "Api"
		sb.WriteString("function " + name + "List() {\n")
		sb.WriteString("  const [rows, setRows] = useState<" + name + "[]>([]);\n")
		sb.WriteString("  useEffect(() => {\n")
		sb.WriteString("    " + apiObj + ".list().then(setRows).catch(() => setRows([]));\n")
		sb.WriteString("  }, []);\n")
		sb.WriteString("  return (\n    <section>\n      <h2>" + name + "</h2>\n      <ul>\n")
		sb.WriteString("        {rows.map((r) => (\n")
		sb.WriteString("          <li key={String(r.id)}>{JSON.stringify(r)}</li>\n")
		sb.WriteString("        ))}\n")
		sb.WriteString("      </ul>\n    </section>\n  );\n}\n\n")
	}
	return sb.String()
}

func lcFirstWeb(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

