// generator/internal/engine/validation_gen.go — v23.8: validation is now TYPED
// and ACTUALLY CALLED. genValidation emits Validate<Type>(m model.<Type>) error
// over the SAME field set the model/store use (fieldsForEntity), and the
// in-memory handler calls it in Create/Update (see genHandlerInMem). WHY: the
// previous Validate<Name>(map[string]interface{}) keyed on raw field names,
// never matched decoded JSON, and was never invoked — dead code. v23.1 (round
// 3) history: shipped a Require helper into the generated validation package so
// it built (was "undefined: Require"); that build fix is preserved.
package engine

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/hpdkhoa/gen-system/generator/internal/schema"
)

// requireHelperSrc is the support code every generated validator uses. Written
// once per generated app into the validation package. v23.8: typed string/int
// required-checks (zero value == missing) replacing the old interface{} form.
const requireHelperSrc = `// Code generated by gen-system. DO NOT EDIT.
package validation

import "fmt"

// RequireString returns an error if a required string field is empty.
func RequireString(field, value string) error {
	if value == "" {
		return fmt.Errorf("%s is required", field)
	}
	return nil
}

// RequireInt returns an error if a required int field is the zero value.
func RequireInt(field string, value int) error {
	if value == 0 {
		return fmt.Errorf("%s is required", field)
	}
	return nil
}
`

// writeRequireHelper writes require.go into the generated validation dir if it
// is not already present. Idempotent and safe to call once per entity.
// v26.58 (D029): returns the write error instead of dropping it.
func writeRequireHelper(path string) error {
	dir := filepath.Join(path, "backend/internal/validation")
	helper := filepath.Join(dir, "require.go")
	// Always overwrite so re-runs converge on the v23.8 typed helper even if an
	// older interface{} require.go is present from a prior generation.
	return writeFileMk(helper, requireHelperSrc)
}

// genValidation writes backend/internal/validation/<route>_validation.go with a
// typed Validate<Type>(m model.<Type>) error. It checks each generated field
// (fieldsForEntity — same set as model/store, so FK and sanitized names line
// up) for its zero value. Synthetic FK fields are NOT required (a child may be
// created before being linked). If there are no checkable fields the validator
// is still emitted (returns nil) so the handler call always compiles.
//
// v26.58 (D029): returns the first write error instead of dropping it.
func genValidation(e schema.Entity, path string) error {
	if err := writeRequireHelper(path); err != nil {
		return err
	}

	n := typeName(e.Name)
	fkTags := map[string]bool{}
	for _, f := range relationFields(e) {
		fkTags[strings.ToLower(jsonTag(f.Name))] = true
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen-system. DO NOT EDIT.\npackage validation\n\n")
	fmt.Fprintf(&b, "import (\n\t\"app/backend/internal/model\"\n)\n\n")
	fmt.Fprintf(&b, "// Validate%[1]s checks required fields on a %[1]s before it is stored.\n", n)
	fmt.Fprintf(&b, "func Validate%s(m model.%s) error {\n", n, n)
	for _, f := range fieldsForEntity(e) {
		tag := jsonTag(f.Name)
		if fkTags[strings.ToLower(tag)] {
			continue // optional foreign key
		}
		ident := exportName(f.Name)
		switch goType(f.Type) {
		case "string":
			fmt.Fprintf(&b, "\tif err := RequireString(%q, m.%s); err != nil {\n\t\treturn err\n\t}\n", tag, ident)
		case "int":
			fmt.Fprintf(&b, "\tif err := RequireInt(%q, m.%s); err != nil {\n\t\treturn err\n\t}\n", tag, ident)
		default:
			// bool/float64: no meaningful "required" zero-check; skip.
		}
	}
	b.WriteString("\treturn nil\n}\n")

	file := filepath.Join(path, "backend/internal/validation/"+e.Name+"_validation.go")
	return writeFileMk(file, b.String())
}
