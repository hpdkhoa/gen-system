// generator/internal/engine/env_gen.go (v23.15): the generated .env/.env.example
// now also write DATABASE_URL (the name the generated Go connector reads first),
// keeping DB_URL for compatibility, so the connection string in .env reaches the app.
package engine

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/hpdkhoa/gen-system/generator/internal/schema"
)

// GenerateEnvFiles writes three files to rootPath:
//
//	.env               actual values; add to .gitignore
//	.env.example       template with placeholder values; commit this
//	docker-compose.yml services derived from architecture components
//
// Components is the arch.Components list from planner_v2:
//
//	e.g. ["api","database","auth","worker"]
//	auth   → adds JWT_SECRET; docker-compose gets no extra service (uses same PG)
//	worker → adds WORKER_CONCURRENCY; docker-compose gets a redis service
//	cache  → docker-compose gets a redis service
func GenerateEnvFiles(entities []schema.Entity, rootPath string, components []string) {
	dbName := inferDBName(entities)
	jwtSecret := generateSecret(32)
	appSecret := generateSecret(16)

	hasAuth := containsComp(components, "auth")
	hasWorker := containsComp(components, "worker")
	hasCache := containsComp(components, "cache")
	hasRedis := hasWorker || hasCache

	// ── .env (real values) ──────────────────────────────────────
	var env strings.Builder
	env.WriteString("# Auto-generated by gen-system. DO NOT commit this file.\n")
	env.WriteString("# Add .env to your .gitignore.\n\n")

	env.WriteString("# Application\n")
	env.WriteString("APP_ENV=development\n")
	env.WriteString("PORT=" + schema.DefaultBackendPort + "\n") // v26.58: the port main.go listens on
	env.WriteString(fmt.Sprintf("APP_SECRET=%s\n\n", appSecret))

	env.WriteString("# Database\n")
	// v23.15: write DATABASE_URL (the name the generated Go connector reads
	// first) and keep DB_URL for backward compatibility. Previously only DB_URL
	// was written while the app read DATABASE_URL, so the .env value never
	// reached the running app.
	env.WriteString(fmt.Sprintf(
		"DATABASE_URL=postgres://postgres:postgres@localhost:5432/%s?sslmode=disable\n",
		dbName))
	env.WriteString(fmt.Sprintf(
		"DB_URL=postgres://postgres:postgres@localhost:5432/%s?sslmode=disable\n",
		dbName))
	env.WriteString(fmt.Sprintf("DATABASE_NAME=%s\n\n", dbName))

	if hasAuth {
		env.WriteString("# Auth\n")
		env.WriteString(fmt.Sprintf("JWT_SECRET=%s\n", jwtSecret))
		env.WriteString("JWT_EXPIRY_HOURS=24\n\n")
	}

	if hasRedis {
		env.WriteString("# Redis\n")
		env.WriteString("REDIS_URL=redis://localhost:6379\n\n")
	}

	if hasWorker {
		env.WriteString("# Worker\n")
		env.WriteString("WORKER_CONCURRENCY=4\n")
		env.WriteString("WORKER_QUEUE=default\n\n")
	}

	writeFile(rootPath, ".env", env.String())

	// ── .env.example (placeholders) ─────────────────────────────
	var ex strings.Builder
	ex.WriteString("# Copy this to .env and fill in real values.\n")
	ex.WriteString("# Commit .env.example, NOT .env.\n\n")
	ex.WriteString("APP_ENV=development\n")
	ex.WriteString("PORT=" + schema.DefaultBackendPort + "\n")
	ex.WriteString("APP_SECRET=your-32-char-secret-here\n\n")
	ex.WriteString(fmt.Sprintf(
		"DATABASE_URL=postgres://user:password@localhost:5432/%s?sslmode=disable\n",
		dbName))
	ex.WriteString(fmt.Sprintf(
		"DB_URL=postgres://user:password@localhost:5432/%s?sslmode=disable\n",
		dbName))
	ex.WriteString(fmt.Sprintf("DATABASE_NAME=%s\n\n", dbName))

	if hasAuth {
		ex.WriteString("JWT_SECRET=your-64-char-jwt-secret-here\n")
		ex.WriteString("JWT_EXPIRY_HOURS=24\n\n")
	}
	if hasRedis {
		ex.WriteString("REDIS_URL=redis://localhost:6379\n\n")
	}
	if hasWorker {
		ex.WriteString("WORKER_CONCURRENCY=4\n")
		ex.WriteString("WORKER_QUEUE=default\n\n")
	}

	writeFile(rootPath, ".env.example", ex.String())

	// ── docker-compose.yml (dynamic per architecture) ───────────
	var dc strings.Builder
	dc.WriteString("# Auto-generated by gen-system.\n")
	dc.WriteString("version: '3.9'\n\nservices:\n")

	// Always: postgres
	dc.WriteString("  postgres:\n")
	dc.WriteString("    image: postgres:16-alpine\n")
	dc.WriteString("    restart: unless-stopped\n")
	dc.WriteString("    environment:\n")
	dc.WriteString("      POSTGRES_USER: postgres\n")
	dc.WriteString("      POSTGRES_PASSWORD: postgres\n")
	dc.WriteString(fmt.Sprintf("      POSTGRES_DB: %s\n", dbName))
	dc.WriteString("    ports:\n")
	dc.WriteString("      - '5432:5432'\n")
	dc.WriteString("    volumes:\n")
	dc.WriteString("      - pg_data:/var/lib/postgresql/data\n\n")

	// Optional: redis (for worker or cache)
	if hasRedis {
		dc.WriteString("  redis:\n")
		dc.WriteString("    image: redis:7-alpine\n")
		dc.WriteString("    restart: unless-stopped\n")
		dc.WriteString("    ports:\n")
		dc.WriteString("      - '6379:6379'\n\n")
	}

	dc.WriteString("volumes:\n  pg_data:\n")

	writeFile(rootPath, "docker-compose.yml", dc.String())

	// ── update .gitignore ────────────────────────────────────────
	appendGitignore(rootPath, []string{".env", "*.env.local"})

	fmt.Printf("[env] ✅ .env + .env.example + docker-compose.yml written\n")
	if hasAuth {
		fmt.Printf("[env]    JWT_SECRET generated (%d chars)\n", len(jwtSecret))
	}
	if hasRedis {
		fmt.Printf("[env]    Redis service added to docker-compose\n")
	}
}

// ─────────────────────────────────────────────
// helpers
// ─────────────────────────────────────────────

func inferDBName(entities []schema.Entity) string {
	if len(entities) == 0 {
		return "app"
	}
	// Use first entity name lowercased as the app identifier
	name := strings.ToLower(entities[0].Name)
	// Strip common suffixes that don't make sense as DB names
	for _, sfx := range []string{"_model", "_entity", "_record"} {
		name = strings.TrimSuffix(name, sfx)
	}
	return name + "_db"
}

func generateSecret(bytes int) string {
	b := make([]byte, bytes)
	if _, err := rand.Read(b); err != nil {
		return strings.Repeat("x", bytes*2)
	}
	return hex.EncodeToString(b)
}

func containsComp(components []string, name string) bool {
	for _, c := range components {
		if strings.EqualFold(c, name) {
			return true
		}
	}
	return false
}

func writeFile(dir, name, content string) {
	path := filepath.Join(dir, name)
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		fmt.Printf("[env] ❌ write failed for %s: %v\n", path, err)
	}
}

func appendGitignore(rootPath string, entries []string) {
	gitignorePath := filepath.Join(rootPath, ".gitignore")
	existing := ""
	if data, err := os.ReadFile(gitignorePath); err == nil {
		existing = string(data)
	}
	var added []string
	for _, e := range entries {
		if !strings.Contains(existing, e) {
			added = append(added, e)
		}
	}
	if len(added) == 0 {
		return
	}
	f, err := os.OpenFile(gitignorePath, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0644)
	if err != nil {
		return
	}
	defer f.Close()
	if existing != "" && !strings.HasSuffix(existing, "\n") {
		fmt.Fprintln(f)
	}
	fmt.Fprintln(f, "# gen-system")
	for _, e := range added {
		fmt.Fprintln(f, e)
	}
}
