// typescript.go (v23.13, Phase 5): tsconfig sets jsx:react-jsx for the .tsx tree; generated interface always includes id:number (backend guarantees it) so Omit<E,'id'> is well-formed and the web project type-checks.
// generator/internal/frontend/typescript.go (v23.11, Phase 2): TypeScript is
// now the shared contract for the web and mobile layers, not a loose side
// artifact. Changes vs v23.10:
//   - belongsTo relations now also emit the FK scalar (e.g. authorId: number)
//     that the JSON API actually returns. Before, only the nested object
//     was typed, so client code reading the FK failed to type-check.
//   - New GenerateAPIClient(): a dependency-free, fully-typed fetch client
//     (one typed function per entity CRUD op) generated from the same schema,
//     so web/mobile import one shared definition instead of redefining shapes.
//   - New GenerateTSConfig(): emits a strict tsconfig.json so the whole
//     frontend/ tree is gated by `tsc --noEmit` (the Phase 2 contract gate).
//
// The original GenerateTypeScript / GenerateTypesBarrel behaviour is preserved
// and extended. v26.57: field keys, types and routes come from the shared
// wire rules in internal/schema (wire.go), the same rules the Go backend uses.
package frontend

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/hpdkhoa/gen-system/generator/internal/schema"
)

// ─────────────────────────────────────────────
// GenerateTypeScript writes a TypeScript interface file for one entity.
//
// Output path: {rootPath}/frontend/src/types/{EntityName}.ts
//
// Example output for a User entity:
//
//	// Auto-generated by gen-system — do not edit
//	export interface User {
//	  id: string;
//	  email: string;
//	  createdAt: string;
//	}
//	export type UserCreateInput = Omit<User, 'id' | 'createdAt'>;
//	export type UserUpdateInput = Partial<UserCreateInput>;
//
// ─────────────────────────────────────────────
func GenerateTypeScript(e schema.Entity, rootPath string) {
	dir := filepath.Join(rootPath, "frontend", "src", "types")
	if err := os.MkdirAll(dir, 0755); err != nil {
		fmt.Printf("[typescript] ❌ mkdir failed for %s: %v\n", dir, err)
		return
	}

	outPath := filepath.Join(dir, e.Name+".ts")

	var sb strings.Builder

	// ── file header ──────────────────────────────────────────────
	sb.WriteString("// Auto-generated by gen-system — do not edit manually.\n")
	sb.WriteString("// Regenerated whenever the " + e.Name + " schema changes.\n\n")

	// ── import related entity types ───────────────────────────────
	// v26.58 (D033): import each target once. Two relations to one target
	// (author_id and editor_id, both User) wrote the same import two times, and
	// tsc rejects a duplicate identifier.
	imported := map[string]bool{}
	for _, rel := range e.Relations {
		if rel.Target != "" && rel.Target != e.Name && !imported[rel.Target] {
			imported[rel.Target] = true
			sb.WriteString(fmt.Sprintf("import type { %s } from './%s';\n", rel.Target, rel.Target))
		}
	}
	if len(e.Relations) > 0 {
		sb.WriteString("\n")
	}

	// ── main interface ────────────────────────────────────────────
	sb.WriteString(fmt.Sprintf("export interface %s {\n", e.Name))

	// Track auto-managed fields for the Omit helper below
	autoFields := []string{"id"}
	// Property names already emitted, so a navigation field never repeats one.
	emitted := map[string]bool{"id": true}

	// v26.57 (D004): the interface lists exactly the JSON keys the generated Go
	// model writes, with the TypeScript form of the Go type it declares. Both
	// sides take the key set from schema.ModelFields and the key from
	// schema.JSONKey. Before, this file built camelCase names of its own
	// (userId, createdAt, passwordHash) while the model wrote user_id,
	// createdat and passwordhash, so the client read undefined; a field such as
	// "due date" even became the invalid property `due date`.
	//
	// The model always carries the auto-increment id (an explicit "id" field
	// in the schema is folded into it), so `id: number` comes first.
	sb.WriteString("  id: number;\n")
	for _, f := range schema.ModelFields(e) {
		key := schema.JSONKey(f.Name)
		optional := ""
		// Timestamps the backend may fill are optional and not client input.
		if strings.HasSuffix(f.Name, "At") || strings.HasSuffix(strings.ToLower(f.Name), "_at") {
			optional = "?"
			autoFields = append(autoFields, key)
		}
		emitted[key] = true
		sb.WriteString(fmt.Sprintf("  %s%s: %s;\n", tsPropName(key), optional, goToTS(schema.GoFieldType(f.Type))))
	}

	// ── relation navigation fields ────────────────────────────────
	// Optional; present only when the API eager-loads the related object.
	singleTargets := map[string]int{}
	for _, rel := range e.Relations {
		if rel.Type == "belongsTo" || rel.Type == "hasOne" {
			singleTargets[rel.Target]++
		}
	}
	for _, rel := range e.Relations {
		var prop, typ string
		switch rel.Type {
		case "hasMany":
			prop, typ = lcFirst(rel.Target)+"s", rel.Target+"[]"
		case "belongsTo", "hasOne":
			prop, typ = lcFirst(rel.Target), rel.Target
			// v26.58 (D033): when two relations share a target, the name
			// "user" fits neither and the second one was dropped. Name each
			// after its foreign key instead (author_id -> author), so both
			// related objects are typed and no property repeats.
			if singleTargets[rel.Target] > 1 {
				if p := navPropFromForeignKey(rel.ForeignKey); p != "" {
					prop = p
				}
			}
		default:
			continue
		}
		if rel.Target == "" || emitted[prop] {
			continue
		}
		emitted[prop] = true
		sb.WriteString(fmt.Sprintf("  %s?: %s;\n", prop, typ))
	}

	sb.WriteString("}\n\n")

	// ── create + update utility types ────────────────────────────
	if len(autoFields) > 0 {
		omitList := "'" + strings.Join(autoFields, "' | '") + "'"
		sb.WriteString(fmt.Sprintf(
			"export type %sCreateInput = Omit<%s, %s>;\n",
			e.Name, e.Name, omitList,
		))
	} else {
		sb.WriteString(fmt.Sprintf("export type %sCreateInput = Omit<%s, 'id'>;\n",
			e.Name, e.Name))
	}
	sb.WriteString(fmt.Sprintf("export type %sUpdateInput = Partial<%sCreateInput>;\n",
		e.Name, e.Name))

	if err := os.WriteFile(outPath, []byte(sb.String()), 0644); err != nil {
		fmt.Printf("[typescript] ❌ write failed for %s: %v\n", outPath, err)
		return
	}
	fmt.Printf("[typescript] ✅ wrote %s\n", outPath)
}

// GenerateTypesBarrel writes frontend/src/types/index.ts that re-exports
// all entity types. Call after generating all entity TypeScript files.
func GenerateTypesBarrel(entities []schema.Entity, rootPath string) {
	dir := filepath.Join(rootPath, "frontend", "src", "types")
	if err := os.MkdirAll(dir, 0755); err != nil {
		return
	}

	var sb strings.Builder
	sb.WriteString("// Auto-generated by gen-system — do not edit manually.\n")
	sb.WriteString("// Re-exports all entity type interfaces.\n\n")
	for _, e := range entities {
		sb.WriteString(fmt.Sprintf(
			"export type { %s, %sCreateInput, %sUpdateInput } from './%s';\n",
			e.Name, e.Name, e.Name, e.Name,
		))
	}

	outPath := filepath.Join(dir, "index.ts")
	_ = os.WriteFile(outPath, []byte(sb.String()), 0644)
	fmt.Printf("[typescript] ✅ wrote types/index.ts (%d entities)\n", len(entities))

	// v23.11 (Phase 2): the barrel is the natural place to also emit the typed
	// API client + the tsconfig that gates the whole tree, since both depend on
	// the complete entity set.
	GenerateAPIClient(entities, rootPath)
	GenerateTSConfig(rootPath)
}

// ─────────────────────────────────────────────
// GenerateAPIClient (v23.11, Phase 2)
//
// Emits frontend/src/api/client.ts: a zero-dependency, fully-typed fetch
// wrapper with one function per entity CRUD operation, all typed against the
// generated interfaces. This is what makes TS the shared contract: web and
// mobile call these typed functions instead of hand-writing fetch calls and
// re-declaring request/response shapes.
//
// Routes match the generated Go backend: collection /<entity>s ,
// item /<entity>s/{id}. (Business-op routes live under /<entity>s-ops/{id}/{op}
// and are intentionally not auto-generated here. Their signatures are
// model-written and entity-specific.)
// ─────────────────────────────────────────────
func GenerateAPIClient(entities []schema.Entity, rootPath string) {
	dir := filepath.Join(rootPath, "frontend", "src", "api")
	if err := os.MkdirAll(dir, 0755); err != nil {
		fmt.Printf("[typescript] ❌ mkdir failed for %s: %v\n", dir, err)
		return
	}

	var sb strings.Builder
	sb.WriteString("// Auto-generated by gen-system — do not edit manually.\n")
	sb.WriteString("// Typed API client. The single source of truth for talking to the\n")
	sb.WriteString("// generated backend; web and mobile both import from here.\n\n")

	// Import every entity's types from the barrel.
	for _, e := range entities {
		sb.WriteString(fmt.Sprintf(
			"import type { %s, %sCreateInput, %sUpdateInput } from '../types';\n",
			e.Name, e.Name, e.Name,
		))
	}
	sb.WriteString("\n")

	// Base URL + a tiny typed request helper.
	sb.WriteString("// API base URL. Override at build time by defining globalThis.API_BASE_URL\n")
	sb.WriteString("// (e.g. via your bundler's define/env plugin). Kept dependency-free so the\n")
	sb.WriteString("// generated client type-checks without @types/node.\n")
	sb.WriteString("const BASE_URL: string =\n")
	sb.WriteString("  ((globalThis as Record<string, unknown>).API_BASE_URL as string | undefined) ||\n")
	sb.WriteString("  'http://localhost:8080';\n\n")

	sb.WriteString("async function request<T>(path: string, init?: RequestInit): Promise<T> {\n")
	sb.WriteString("  const res = await fetch(BASE_URL + path, {\n")
	sb.WriteString("    headers: { 'Content-Type': 'application/json' },\n")
	sb.WriteString("    ...init,\n")
	sb.WriteString("  });\n")
	sb.WriteString("  if (!res.ok) {\n")
	sb.WriteString("    const body = await res.text();\n")
	sb.WriteString("    throw new Error(`${res.status} ${res.statusText}: ${body}`);\n")
	sb.WriteString("  }\n")
	sb.WriteString("  if (res.status === 204) return undefined as unknown as T;\n")
	sb.WriteString("  return (await res.json()) as T;\n")
	sb.WriteString("}\n\n")

	// One typed CRUD block per entity.
	for _, e := range entities {
		// v26.57 (D002): the path the generated backend registers. Before, this
		// was "/" + lcFirst(name) + "s" ("/blogPosts"), while the backend served
		// "/blogposts"; Go's ServeMux matches case exactly, so every call of a
		// multi-word entity got 404.
		coll := schema.CollectionPath(e.Name)
		sb.WriteString(fmt.Sprintf("// ── %s ──────────────────────────────────────────\n", e.Name))
		sb.WriteString(fmt.Sprintf("export const %s = {\n", lcFirst(e.Name)+"Api"))
		sb.WriteString(fmt.Sprintf("  list: (): Promise<%s[]> =>\n", e.Name))
		sb.WriteString(fmt.Sprintf("    request<%s[]>('%s'),\n", e.Name, coll))
		sb.WriteString(fmt.Sprintf("  get: (id: number): Promise<%s> =>\n", e.Name))
		sb.WriteString(fmt.Sprintf("    request<%s>(`%s/${id}`),\n", e.Name, coll))
		sb.WriteString(fmt.Sprintf("  create: (input: %sCreateInput): Promise<%s> =>\n", e.Name, e.Name))
		sb.WriteString(fmt.Sprintf("    request<%s>('%s', { method: 'POST', body: JSON.stringify(input) }),\n", e.Name, coll))
		sb.WriteString(fmt.Sprintf("  update: (id: number, input: %sUpdateInput): Promise<%s> =>\n", e.Name, e.Name))
		sb.WriteString(fmt.Sprintf("    request<%s>(`%s/${id}`, { method: 'PUT', body: JSON.stringify(input) }),\n", e.Name, coll))
		sb.WriteString(fmt.Sprintf("  remove: (id: number): Promise<void> =>\n"))
		sb.WriteString(fmt.Sprintf("    request<void>(`%s/${id}`, { method: 'DELETE' }),\n", coll))
		sb.WriteString("};\n\n")
	}

	outPath := filepath.Join(dir, "client.ts")
	if err := os.WriteFile(outPath, []byte(sb.String()), 0644); err != nil {
		fmt.Printf("[typescript] ❌ write failed for %s: %v\n", outPath, err)
		return
	}
	fmt.Printf("[typescript] ✅ wrote api/client.ts (%d entities)\n", len(entities))
}

// ─────────────────────────────────────────────
// GenerateTSConfig (v23.11, Phase 2)
//
// Emits frontend/tsconfig.json with strict type-checking so the whole
// generated frontend/ tree can be gated by `tsc --noEmit`. This is the Phase 2
// contract gate: if the generated types + client don't type-check, the build
// fails here rather than at runtime in the browser.
//
// Idempotent-ish: it overwrites so the gate config stays canonical across
// regenerations. "dom" lib is included for fetch/RequestInit; "es2020" for the
// language level.
// ─────────────────────────────────────────────
func GenerateTSConfig(rootPath string) {
	dir := filepath.Join(rootPath, "frontend")
	if err := os.MkdirAll(dir, 0755); err != nil {
		return
	}
	cfg := `{
  "compilerOptions": {
    "target": "ES2020",
    "module": "ESNext",
    "moduleResolution": "bundler",
    "lib": ["ES2020", "DOM", "DOM.Iterable"],
    "jsx": "react-jsx",
    "strict": true,
    "noEmit": true,
    "skipLibCheck": true,
    "esModuleInterop": true,
    "forceConsistentCasingInFileNames": true
  },
  "include": ["src/**/*.ts", "src/**/*.tsx"]
}
`
	outPath := filepath.Join(dir, "tsconfig.json")
	_ = os.WriteFile(outPath, []byte(cfg), 0644)
	fmt.Printf("[typescript] ✅ wrote frontend/tsconfig.json (tsc --noEmit gate)\n")
}

// goToTS maps the Go type of a generated model field (schema.GoFieldType) to
// the TypeScript type of its JSON value.
func goToTS(goType string) string {
	switch goType {
	case "int", "float64":
		return "number"
	case "bool":
		return "boolean"
	default:
		return "string"
	}
}

// tsPropName writes a JSON key as a TypeScript property name, quoted when the
// key is not a valid identifier (a JSON key can start with a digit).
func tsPropName(key string) string {
	if key != "" && (key[0] < '0' || key[0] > '9') {
		return key
	}
	return "'" + key + "'"
}

// navPropFromForeignKey derives a navigation property name from a foreign key:
// its JSON key without the trailing "_id" ("author_id" and "AuthorID" ->
// "author"). It returns "" when nothing is left or the name is not a valid
// identifier.
func navPropFromForeignKey(fk string) string {
	if strings.TrimSpace(fk) == "" {
		return ""
	}
	key := strings.TrimSuffix(schema.JSONKey(schema.FKFieldName(fk)), "_id")
	if key == "" || key == "id" || (key[0] >= '0' && key[0] <= '9') {
		return ""
	}
	return key
}

func lcFirst(s string) string {
	if len(s) == 0 {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}
