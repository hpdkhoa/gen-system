package github

import (
	"encoding/base64"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// GeneratedPR holds the result of a PR-creation attempt.
type GeneratedPR struct {
	Number int    `json:"number"`
	URL    string `json:"url"`
	Branch string `json:"branch"`
	Files  int    `json:"files_pushed"`
}

// CreateBuildPR creates a GitHub branch, pushes generated Go + JSX files,
// and opens a draft pull request for human review.
//
// rootPath is the gen-system project root (contains backend/ and frontend/).
// goal is the natural-language build goal. The PR title/body use it.
//
// Only files under backend/internal/ and frontend/src/ are pushed.
// The function is intentionally conservative: it skips files that fail
// to encode, and opens a draft PR so no CI is triggered until a human
// promotes it.
func CreateBuildPR(rootPath, goal string) (GeneratedPR, error) {
	cfg, err := LoadConfig()
	if err != nil {
		return GeneratedPR{}, err
	}

	client := NewClient(cfg)

	// 1. Get current HEAD SHA of base branch
	baseSHA, err := client.GetRef("heads/" + cfg.Base)
	if err != nil {
		return GeneratedPR{}, fmt.Errorf("get base ref: %w", err)
	}

	// 2. Create a uniquely-named feature branch
	stamp := time.Now().Format("20060102-150405")
	// Sanitize goal for branch name
	safeName := strings.Map(func(r rune) rune {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-' {
			return r
		}
		if r == ' ' || r == '_' {
			return '-'
		}
		if r >= 'A' && r <= 'Z' {
			return r + 32 // lowercase
		}
		return -1 // drop
	}, goal)
	if len(safeName) > 40 {
		safeName = safeName[:40]
	}
	branch := fmt.Sprintf("gen/%s-%s", safeName, stamp)

	if err := client.CreateRef(branch, baseSHA); err != nil {
		return GeneratedPR{}, fmt.Errorf("create branch: %w", err)
	}

	// 3. Walk generated files and push them
	dirs := []string{
		filepath.Join(rootPath, "backend", "internal"),
		filepath.Join(rootPath, "frontend", "src"),
	}

	pushed := 0
	for _, dir := range dirs {
		if _, err := os.Stat(dir); err != nil {
			continue // directory doesn't exist yet; skip
		}
		err := filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
			if err != nil || info.IsDir() {
				return nil
			}
			ext := strings.ToLower(filepath.Ext(path))
			if ext != ".go" && ext != ".jsx" && ext != ".ts" && ext != ".tsx" {
				return nil
			}

			data, err := os.ReadFile(path)
			if err != nil {
				fmt.Printf("  [github] ⚠️  skipping %s: %v\n", path, err)
				return nil
			}

			// Path relative to rootPath for the repo tree
			relPath, err := filepath.Rel(rootPath, path)
			if err != nil {
				return nil
			}
			relPath = filepath.ToSlash(relPath)

			encoded := base64.StdEncoding.EncodeToString(data)
			commitMsg := fmt.Sprintf("gen: add %s", filepath.Base(path))

			if err := client.UpsertFile(relPath, encoded, commitMsg, branch, ""); err != nil {
				fmt.Printf("  [github] ⚠️  push failed for %s: %v\n", relPath, err)
				return nil
			}
			pushed++
			fmt.Printf("  [github] ✅ pushed %s\n", relPath)
			return nil
		})
		if err != nil {
			fmt.Printf("  [github] ⚠️  walk error in %s: %v\n", dir, err)
		}
	}

	if pushed == 0 {
		return GeneratedPR{}, fmt.Errorf("no files were pushed; check that the build generated output")
	}

	// 4. Open draft PR
	prBody := fmt.Sprintf(`## Generated by gen-system

**Goal:** %s

**Files changed:** %d

---
This is a draft PR created automatically after a successful gen-system build.

Review the generated code, run tests, then mark as ready for review.

> Auto-generated · [gen-system](https://github.com/yourusername/gen-system)
`, goal, pushed)

	prTitle := fmt.Sprintf("gen: %s", goal)
	if len(prTitle) > 72 {
		prTitle = prTitle[:72]
	}

	pr, err := client.CreatePR(PRRequest{
		Title: prTitle,
		Body:  prBody,
		Head:  branch,
		Base:  cfg.Base,
		Draft: true,
	})
	if err != nil {
		return GeneratedPR{}, fmt.Errorf("create PR: %w", err)
	}

	fmt.Printf("  [github] 🔀 PR #%d opened: %s\n", pr.Number, pr.HTMLURL)

	return GeneratedPR{
		Number: pr.Number,
		URL:    pr.HTMLURL,
		Branch: branch,
		Files:  pushed,
	}, nil
}
